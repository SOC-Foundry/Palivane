_UA = {"claude-code": "palivane-hook", "cursor": "palivane-cursor-hook"}


def _hit_for(event: dict):
    """The AI tool a capture plane would name for this event: by destination for what was pasted into a
    web tool, by the plane's own identity for a coding agent's tool call (as discovery.record_capture and
    record_capture_client do)."""
    md = event.get("metadata") or {}
    if event["surface"] == Surface.AI_USAGE:
        return ai_catalog.classify(md.get("destination", "")) or ai_catalog.classify_client(md.get("ua", ""))
    if event["surface"] == Surface.MCP:
        return ai_catalog.classify_client(_UA.get(event["subject"].split(" · ")[0], ""))
    return None


class Captures:
    """What the capture planes saw, noted as each finding is written, so Discovery can be built from
    it afterwards and agree with the Findings page."""

    def __init__(self):
        self.rows: list[tuple] = []

    def add(self, event: dict, row: Finding) -> None:
        hit = _hit_for(event)
        if hit:
            self.rows.append((row.sender, hit, row.signals, row.risk_score, row.created_at))


# --- clearing, so a re-run starts from the same place ------------------------------------------------------

def clear(db, tenant: Tenant) -> None:
    """Remove what a previous run wrote. Derived tables go outright (like the findings); the identity
    objects only by the names this module gives them, so something made by hand is left alone."""
    tid = tenant.id
    for model in (AuditLog, DiscoveredUsage, SensorHeartbeat, ContentFingerprint, JoinRequest):
        db.query(model).filter(model.tenant_id == tid).delete(synchronize_session=False)
    db.query(OAuthToken).filter(OAuthToken.tenant_id == tid, OAuthToken.client_id.like("demo-%")
                                ).delete(synchronize_session=False)
    db.query(OAuthClient).filter(OAuthClient.client_id.in_([a[0] for a in APPS])).delete(synchronize_session=False)
    db.query(ApiKey).filter(ApiKey.tenant_id == tid, ApiKey.label.in_([k[0] for k in KEYS])
                            ).delete(synchronize_session=False)
    db.query(EnrollmentToken).filter(EnrollmentToken.tenant_id == tid, EnrollmentToken.label.in_([e[0] for e in ENROLL])
                                     ).delete(synchronize_session=False)
    db.query(Agent).filter(Agent.tenant_id == tid, Agent.name.in_([a[0] for a in AGENTS])
                           ).delete(synchronize_session=False)
    db.query(AgentRole).filter(AgentRole.tenant_id == tid, AgentRole.name.in_([r[0] for r in ROLES])
                               ).delete(synchronize_session=False)
    db.query(TenantDomain).filter(TenantDomain.tenant_id == tid, TenantDomain.domain == DOMAIN
                                  ).delete(synchronize_session=False)
    db.query(User).filter(User.tenant_id == tid, User.email.in_([u[0] for u in USERS])
                          ).delete(synchronize_session=False)
    db.flush()


def documents(db, tenant: Tenant, now: datetime) -> None:
    """Fingerprint the documents the org has "scanned at rest" (what the Drive, SharePoint and Salesforce
    connectors do), so a prompt that copies from one can be traced back to it."""
    for source, ref, title, owner, sentences, days in DOCS:
        content_origin.store_fingerprint(db, tenant.id, source, ref, title, owner, " ".join(sentences), sensitive=True)
    db.flush()
    rows = db.query(ContentFingerprint).filter(ContentFingerprint.tenant_id == tenant.id).all()
    if len(rows) != len(DOCS):            # store_fingerprint swallows its own failures; the demo must not
        raise RuntimeError(f"expected {len(DOCS)} document sketches, found {len(rows)}")
    by_ref = {r.ref: r for r in rows}
    for source, ref, title, owner, sentences, days in DOCS:
        by_ref[ref].updated_at = now - timedelta(days=days)


# --- writing the org ---------------------------------------------------------------------------------------

def _ago(now: datetime, days: float = 0, hours: float = 0) -> datetime:
    return now - timedelta(days=days, hours=hours)


def apply(db, tenant: Tenant, admin: str, now: datetime, captures: Captures) -> dict:
    """Write everything above for `tenant`; `captures` is what the findings already written look like
    from the capture planes. Returns what it wrote."""
    unusable = hash_password(secrets.token_urlsafe(32))    # nobody is ever told it

    # the console's people, and the domain they sign in from
    users = {u.email: u for u in db.query(User).filter(User.tenant_id == tenant.id).all()}
    for email, role, active, days in USERS:
        u = User(tenant_id=tenant.id, email=email, password_hash=unusable, role=role, active=active,
                 created_at=_ago(now, days))
        db.add(u)
        users[email] = u
    # A domain can be claimed by one org in the whole install. If someone else has this one, the demo org
    # goes without it (and without the join request that depends on it) rather than failing the seed.
    claimed = db.query(TenantDomain).filter(TenantDomain.domain == DOMAIN).first() is None
    if claimed:
        db.add(TenantDomain(tenant_id=tenant.id, domain=DOMAIN, token=secrets.token_hex(16), verified=True,
                            created_at=_ago(now, 41), verified_at=_ago(now, 41, -1)))
        for email, days in JOIN_REQUESTS:
            db.add(JoinRequest(tenant_id=tenant.id, email=email, password_hash=unusable, status="pending",
                               email_verified=False, created_at=_ago(now, days)))
    if not (tenant.sanctioned_ai_tools or "").strip():
        tenant.sanctioned_ai_tools = SANCTIONED
    db.flush()

    # document leaks and agent-to-agent traffic: findings, scored by the engine like the rest
    extra = 0
    for kind, rows in (("leak", LEAKS), ("a2a", A2A)):
        for age, events, last, event in rows:
            created = _ago(now, age, (extra * 3) % 7)
            seen = created if last is None else max(created, _ago(now, last, (extra * 5) % 6))
            fields = {"created_at": created, "last_seen": seen, "seen_count": events}
            if kind == "a2a":
                fields["agent"] = event["sender"]
            row = seed_history.score(tenant, event, db=db, **fields)
            db.add(row)
            captures.add(event, row)
            extra += 1
    db.flush()

    _discovery(db, tenant, now, captures)
    _sensors(db, tenant, now)
    keys, tokens = _credentials(db, tenant, now, users, admin)
    _agents(db, tenant, now)
    _audit(db, tenant, admin, now, users, keys, tokens, claimed)
    db.commit()
    return {"users": len(USERS), "documents": len(DOCS), "leaks": len(LEAKS), "a2a": len(A2A),
            "agents": len(AGENTS), "sensors": len(SENSORS), "keys": len(KEYS)}


def _discovery(db, tenant: Tenant, now: datetime, captures: Captures) -> None:
    """The inventory, from the two sources the product has: log lines from the CASB / proxy, and what a
    capture plane saw (the findings, with whether they carried sensitive data and how risky they were)."""
    events = []
    for dest, lines in _LOG.items():
        for who, count, days in lines:
            events.append(SimpleNamespace(actor=_actor(who), destination=dest, team=_team(who), count=count,
                                          last_seen=_ago(now, days).isoformat()))
    discovery.ingest_logs(db, tenant.id, events)
    for actor, hit, signals, risk, when in captures.rows:
        cats = {s.get("category") for s in (signals or [])}
        discovery._upsert(db, tenant.id, actor, hit, source="capture", sensitive=bool(cats & discovery._SENSITIVE),
                          risk=int(risk or 0), team=_team_of(actor), when=when)
    db.flush()


def _sensors(db, tenant: Tenant, now: datetime) -> None:
    latest = client_versions()
    for actor, plane, tool, client, version, agent, agent_v, first, last_h, count, misses in SENSORS:
        if version == "current":
            version = latest.get(client, "1.0.0")
        db.add(SensorHeartbeat(
            tenant_id=tenant.id, actor=actor, plane=plane, tool=tool, first_seen=_ago(now, first), last_seen=_ago(now, 0, last_h), count=count,
            client=client, client_version=version, agent=agent, agent_version=agent_v,
            parse_miss_count=misses, last_parse_miss=_ago(now, 0, last_h) if misses else None,
            **_scan_fails(now, (actor, plane, tool))))


def _scan_fails(now: datetime, scope: tuple) -> dict:
    if scope not in SCAN_FAILS:
        return {}
    reasons, first_h, last_h = SCAN_FAILS[scope]
    return {"scan_fail_count": sum(reasons.values()), "scan_fail_reasons": dict(reasons),
            "first_scan_fail": _ago(now, 0, first_h), "last_scan_fail": _ago(now, 0, last_h)}


