"""The org around the demo's findings: the people, devices, agents, credentials and trail that fill the
rest of the console.

Findings alone fill one page. Without this, Discovery says "0 AI tools", Exposure "No leaked documents
yet", Fleet "No sensor activity captured yet", Agents "No agents yet", Connections "No keys yet" and Audit
"No admin activity recorded yet", because the seed wrote findings and nothing else, and those pages read
other tables. An admin walking an evaluator through the demo org (or a design partner clicking around a
trial) saw a product that was mostly empty.

How it stays honest:

- What the product derives is derived here the same way. Discovery is built by the discovery module's own
  ingest (log lines) and capture upsert (from the findings above), so its numbers agree with the Findings
  page; a leak is traced to the documents the org "scanned at rest" by the capture path's own matcher
  (service.trace_origin), so Exposure and the finding's origin agree with each other; the audit trail is
  written from what the rest of the seed did (every review, every allowlist entry), not invented beside it.
- Nothing here is a working credential. Keys, agent tokens and enrollment tokens are generated by the
  product's own generators and only the hash is kept; the plaintext is dropped. The unusable password on a
  demo user is never shown to anyone.
- The demo org is disposable, like its findings: a run replaces the derived tables (discovery, fleet,
  document index, audit trail) outright and replaces the identity objects it created (users, keys, tokens,
  agents, roles, apps) by name, so a re-run starts from the same place and a credential somebody made in
  the demo org by hand is left alone.

Content is synthetic throughout (invented people, company and documents). Dates are relative to the run.
"""

